#pragma once

#include <homestore/replication/repl_dev.hpp>
#include "homeblks_impl.hpp"

namespace homeblocks {

class HomeBlocksImpl;

class HBListener : public homestore::repl_dev_listener {
public:
    explicit HBListener(HomeBlocksImpl* hb) : hb_(hb) {}

    ~HBListener() = default;

    void on_commit(int64_t lsn, sisl::blob const& header, sisl::blob const& key,
                   std::vector< homestore::multi_blk_id > const& blkids,
                   cintrusive< homestore::repl_req_ctx >& ctx) override;

    bool on_pre_commit(int64_t lsn, const sisl::blob& header, const sisl::blob& key,
                       cintrusive< homestore::repl_req_ctx >& ctx) override;

    void on_error(homestore::ReplServiceError error, const sisl::blob& header, const sisl::blob& key,
                  cintrusive< homestore::repl_req_ctx >& ctx) override;

    homestore::result< homestore::blk_alloc_hints >
    get_blk_alloc_hints(sisl::blob const& header, uint32_t data_size,
                        cintrusive< homestore::repl_req_ctx >& hs_ctx) override;
    // group_id is the uuid generated by home_blocks when create_volume->create_repl_dev(gid) is called;
    // when volume is being destroyed, on_destroy is going to be triggered to listener that this volume's gid is
    // destroyed;
    void on_destroy(const homestore::group_id_t& group_id) override;

    void on_start_replace_member(const std::string& task_id, const homestore::replica_member_info& member_out,
                                 const homestore::replica_member_info& member_in, homestore::trace_id_t tid) override {}
    void on_complete_replace_member(const std::string& task_id, const homestore::replica_member_info& member_out,
                                    const homestore::replica_member_info& member_in,
                                    homestore::trace_id_t tid) override {}
    void on_clean_replace_member_task(const std::string& task_id, const homestore::replica_member_info& member_out,
                                      const homestore::replica_member_info& member_in,
                                      homestore::trace_id_t tid) override {}
    void on_remove_member(const homestore::replica_id_t&, homestore::trace_id_t) override {}
    void on_rollback(int64_t lsn, const sisl::blob& header, const sisl::blob& key,
                     cintrusive< homestore::repl_req_ctx >& ctx) override {}
    void on_restart() override { LOGD("HBListener::on_restart()"); }
    /// @brief Called when the snapshot is being created by nuraft;
    homestore::async_status create_snapshot(std::shared_ptr< homestore::snapshot_context > context) override {
        co_return homestore::ok();
    }
    bool apply_snapshot(std::shared_ptr< homestore::snapshot_context > context) override { return true; }
    std::shared_ptr< homestore::snapshot_context > last_snapshot() override { return nullptr; }
    int read_snapshot_obj(std::shared_ptr< homestore::snapshot_context > context,
                          std::shared_ptr< homestore::snapshot_obj > snp_obj) override {
        return 0;
    }
    void write_snapshot_obj(std::shared_ptr< homestore::snapshot_context > context,
                            std::shared_ptr< homestore::snapshot_obj > snp_obj) override {}
    void free_user_snp_ctx(void*& user_snp_ctx) override {}
    void on_no_space_left(homestore::repl_lsn_t lsn, sisl::blob const& header) override {}
    void notify_committed_lsn(int64_t lsn) override {}
    void on_config_rollback(int64_t lsn) override {}
    // <<<<< end of r1: mockup apis >>>>>>>>>>

private:
    HomeBlocksImpl* hb_{nullptr};
};

// Per-group listener of a CRAFT instance. HomeStore asks for a group's listener when the group is created, joined or
// recovered: before the volume, and its CraftReplDev, exist on this node. So this one lives at the HomeBlocks level: it
// applies the group's CreateVolume and forwards every other CRAFT entry to the volume's CraftReplDev.
class CraftGroupListener : public homestore::repl_dev_listener {
public:
    // `recovered`: HomeStore is recovering this group at restart, so its log replay is still to come.
    CraftGroupListener(HomeBlocksImpl* hb, homestore::group_id_t group_id, bool recovered) :
            hb_{hb}, group_id_{group_id}, replaying_{recovered} {}

    void on_commit(int64_t lsn, sisl::blob const& header, sisl::blob const& key,
                   std::vector< homestore::multi_blk_id > const& blkids,
                   cintrusive< homestore::repl_req_ctx >& ctx) override;
    void on_rollback(int64_t lsn, sisl::blob const& header, sisl::blob const& key,
                     cintrusive< homestore::repl_req_ctx >& ctx) override;
    void on_error(homestore::ReplServiceError error, sisl::blob const& header, sisl::blob const& key,
                  cintrusive< homestore::repl_req_ctx >& ctx) override;
    void on_log_replay_done(homestore::group_id_t const&) override { replaying_ = false; }

private:
    // The volume whose CraftReplDev this group's entries go to, or null (logged) if there is none here (yet).
    volume_handle craft_volume(int64_t lsn) const;

    HomeBlocksImpl* hb_;
    homestore::group_id_t group_id_;
    std::atomic< bool > replaying_;
};
} // namespace homeblocks
